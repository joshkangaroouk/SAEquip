/**
 * Hire/Purchase and the SA Rental logo (Josh, 15 Oct 2026).
 *
 *   npm run catalogue:hire-purchase --workspace=backend [-- --confirm]
 *
 *   1. The store's existing "Hire/Purchase" option (EX Heater's; Hire first,
 *      so Duda pre-selects Hire) on every VISIBLE product that is not an
 *      accessory. Accessories get none: removed if one has it.
 *   2. SA Rental logo ON for every visible non-accessory, OFF for every
 *      visible accessory.
 *
 * Hidden products (the three weekly rentals) are never touched. Options go
 * through updateOptionsPreservingVariations(); a product whose variations
 * carry data that the change would lose stops the run before any write.
 * "Accessory" is HubProduct.isAccessory. Dry run by default.
 */
import "dotenv/config";
import { prisma } from "../prisma.js";
import { duda } from "../services/duda.js";
import { updateOptionsPreservingVariations } from "../services/productOptions.js";

const confirm = process.argv.includes("--confirm");
const OPTION_NAME = "Hire/Purchase";
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function main() {
  const option = ((await duda.listOptions()).results ?? []).find((o) => o.name === OPTION_NAME);
  if (!option) throw new Error(`no "${OPTION_NAME}" option in the store`);
  const choices = (option.choices ?? []).map((c) => ({ id: c.id, value: (c as { value?: string }).value }));
  if (choices.map((c) => c.value).join("|") !== "Hire|Purchase") throw new Error(`"${OPTION_NAME}" choices are ${choices.map((c) => c.value).join(", ")}, expected Hire, Purchase`);

  const rental = await prisma.logo.findMany({ where: { kind: "SA_LOGO" }, include: { mediaAsset: { select: { filename: true } } } });
  const rentalLogo = rental.filter((l) => /rental/i.test(`${l.label} ${l.alt} ${l.mediaAsset.filename}`));
  if (rentalLogo.length !== 1) throw new Error(`expected one SA Rental logo, found ${rentalLogo.length}`);
  const rentalId = rentalLogo[0].id;

  const all = await duda.listAllProducts();
  const hub = await prisma.hubProduct.findMany({ select: { id: true, dudaProductId: true, name: true, isAccessory: true, logos: { select: { logoId: true } } } });
  const hubBy = new Map(hub.map((h) => [h.dudaProductId, h]));
  const visible = all.filter((p) => p.status === "ACTIVE");
  const missing = visible.filter((p) => !hubBy.has(p.id));
  if (missing.length) throw new Error(`no Hub row for ${missing.map((p) => p.name).join(", ")}`);

  const has = (p: (typeof all)[number]) => (p.options ?? []).some((o) => o.id === option.id);
  const attach = visible.filter((p) => !hubBy.get(p.id)!.isAccessory && !has(p));
  const detach = visible.filter((p) => hubBy.get(p.id)!.isAccessory && has(p));
  const rentalOn = visible.filter((p) => !hubBy.get(p.id)!.isAccessory && !hubBy.get(p.id)!.logos.some((l) => l.logoId === rentalId));
  const rentalOff = visible.filter((p) => hubBy.get(p.id)!.isAccessory && hubBy.get(p.id)!.logos.some((l) => l.logoId === rentalId));

  // A product's variations are regenerated by any option change; any data on
  // them (SKU, price, status) must not be lost silently.
  const atRisk = [...attach, ...detach].filter((p) =>
    (p.variations ?? []).some((v) => v.sku || (v.price_difference && Number(v.price_difference) !== 0) || (v.status && v.status !== "ACTIVE")),
  );
  if (atRisk.length) throw new Error(`variation data would be lost on: ${atRisk.map((p) => p.name).join(", ")}`);

  const nonAcc = visible.filter((p) => !hubBy.get(p.id)!.isAccessory).length;
  console.log(`\n${confirm ? "Applying" : "Dry run —"} Hire/Purchase and SA Rental`);
  console.log(`  visible ${visible.length}: ${nonAcc} non-accessory, ${visible.length - nonAcc} accessories; hidden untouched: ${all.filter((p) => p.status !== "ACTIVE").map((p) => p.name).join("; ")}`);
  console.log(`  "${OPTION_NAME}" (${choices.map((c) => c.value).join(", ")}) to attach: ${attach.length}; already on: ${visible.filter(has).length}; to remove from accessories: ${detach.length}`);
  for (const p of attach) if (p.options?.length) console.log(`    ${p.name}: alongside ${p.options.map((o) => o.name).join(", ")} (${p.variations?.length ?? 0} variations → ${(p.variations?.length || 1) * 2})`);
  console.log(`  SA Rental ON: ${rentalOn.length} (${rentalOn.map((p) => p.name).join("; ")})`);
  console.log(`  SA Rental OFF: ${rentalOff.length} (${rentalOff.map((p) => p.name).join("; ")})`);
  if (!confirm) { console.log("\nNothing written.\n"); return; }

  const failed: string[] = [];
  for (const p of [...attach, ...detach]) {
    const keep = (p.options ?? []).filter((o) => o.id !== option.id).map((o) => ({ id: o.id, choiceIds: (o.choices ?? []).map((c) => c.id) }));
    const refs = attach.includes(p) ? [...keep, { id: option.id, choiceIds: choices.map((c) => c.id) }] : keep;
    try {
      const r = await updateOptionsPreservingVariations(p.id, refs);
      if (r.dropped.length || r.failed.length) failed.push(`${p.name}: dropped ${r.dropped.length}, failed ${r.failed.length}`);
    } catch (e) {
      failed.push(`${p.name}: ${e instanceof Error ? e.message : e}`);
    }
    await sleep(300);
  }
  await prisma.productLogo.createMany({ data: rentalOn.map((p) => ({ hubProductId: hubBy.get(p.id)!.id, logoId: rentalId })), skipDuplicates: true });
  await prisma.productLogo.deleteMany({ where: { logoId: rentalId, hubProductId: { in: rentalOff.map((p) => hubBy.get(p.id)!.id) } } });

  // Verify against what Duda and the Hub now hold.
  const after = await duda.listAllProducts();
  const hubAfter = await prisma.hubProduct.findMany({ select: { dudaProductId: true, isAccessory: true, logos: { select: { logoId: true } } } });
  const hA = new Map(hubAfter.map((h) => [h.dudaProductId, h]));
  const wrong: string[] = [];
  for (const p of after) {
    const h = hA.get(p.id);
    if (p.status !== "ACTIVE" || !h) continue;
    const opt = (p.options ?? []).find((o) => o.id === option.id);
    const rentalNow = h.logos.some((l) => l.logoId === rentalId);
    if (!h.isAccessory && (!opt || (opt.choices ?? []).map((c) => c.id).join() !== choices.map((c) => c.id).join())) wrong.push(`${p.name}: Hire/Purchase missing`);
    if (h.isAccessory && opt) wrong.push(`${p.name}: accessory has Hire/Purchase`);
    if (rentalNow === h.isAccessory) wrong.push(`${p.name}: SA Rental ${rentalNow ? "on" : "off"}`);
  }
  console.log(`  ✓ written. Check: ${wrong.length ? "✗ " + wrong.join("; ") : "every visible product as planned"}${failed.length ? `\n  ✗ ${failed.join("; ")}` : ""}\n`);
  if (wrong.length || failed.length) process.exitCode = 1;
}

main()
  .catch((err) => {
    console.error("\n✗ Failed:", err instanceof Error ? err.message : err, "\n");
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
