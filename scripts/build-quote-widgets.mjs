#!/usr/bin/env node
/**
 * The three quote widgets live in Duda's Widget Builder and are PASTED there by
 * hand (see CLAUDE.md, "Quote Requests"). Their source is duda-widgets/:
 *
 *   duda-widgets/quote-shared.js          the basket store + languages, shared
 *   duda-widgets/<widget>/<widget>.html   one per widget, .css and .js likewise
 *
 * This script copies quote-shared.js into each widget's JS (between the
 * ">>> shared quote code" and "<<< shared quote code" markers) and rebuilds
 * 3-widgets-in-duda.md — the file to paste from — from those files.
 *
 * OTHER_WIDGETS get the same shared block for its language helpers, but are
 * pasted from their own three files rather than from 3-widgets-in-duda.md.
 *
 *   node scripts/build-quote-widgets.mjs           write
 *   node scripts/build-quote-widgets.mjs --check   fail if anything is stale (pre-push)
 *
 * ⚠️ Edit the files in duda-widgets/, never 3-widgets-in-duda.md: it is
 * overwritten. And edit the shared block in quote-shared.js, never inside one
 * widget, or the three drift apart — which is what the markers exist to stop.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const W = path.join(ROOT, "duda-widgets");
const check = process.argv.includes("--check");

const START = "/* >>> shared quote code (duda-widgets/quote-shared.js) */";
const END = "/* <<< shared quote code */";
const shared = readFileSync(path.join(W, "quote-shared.js"), "utf8").trimEnd();

const WIDGETS = [
  { dir: "basket-page", title: "Basket Page widget", duda: "SAEquip - Basket Page" },
  { dir: "quote-header", title: "Quote Basket Header widget", duda: "SAEquip - Quote Basket Header" },
  { dir: "add-to-quote", title: "Add to Quote widget", duda: "SAEquip - Add to Quote" },
];

/* Pasted from duda-widgets/<dir>/ directly; they use the shared block's
   SAEquipQuoteI18n (the page's language, and translating marked text). */
const OTHER_WIDGETS = [{ dir: "find-a-distributor" }];

const stale = [];
const write = (file, content) => {
  const before = (() => {
    try {
      return readFileSync(file, "utf8");
    } catch {
      return null;
    }
  })();
  if (before === content) return;
  if (check) stale.push(path.relative(ROOT, file));
  else writeFileSync(file, content);
};

/** The widget's JS with the shared block copied in, written back to its file. */
function inline(dir) {
  let js = readFileSync(path.join(W, dir, `${dir}.js`), "utf8").trimEnd();
  const a = js.indexOf(START);
  const b = js.indexOf(END);
  if (a === -1 || b === -1 || b < a) throw new Error(`${dir}.js: the shared-code markers are missing`);
  js = `${js.slice(0, a)}${START}\n${shared}\n${js.slice(b)}`;
  write(path.join(W, dir, `${dir}.js`), `${js}\n`);
  return js;
}

const parts = [];
for (const w of WIDGETS) {
  const read = (ext) => readFileSync(path.join(W, w.dir, `${w.dir}.${ext}`), "utf8").trimEnd();
  const js = inline(w.dir);
  parts.push(`${w.title}:\n\nHTML:\n${read("html")}\nCSS:\n${read("css")}\nJS:\n${js}\n`);
}
for (const w of OTHER_WIDGETS) inline(w.dir);

const doc = `THE THREE QUOTE WIDGETS — what to paste into Duda's Widget Builder.

⚠️ GENERATED by scripts/build-quote-widgets.mjs from the files in
duda-widgets/. Edit those, then re-run it; never edit this file directly.

UPDATED 2026-10-12 — the basket keeps two lines for one product apart when
their options differ, even where the page's option ids could not be read
(they used to merge, and the second choice vanished from the quote). And
the widgets keep working when a browser blocks site data (they used to fail
at load, and the basket form could then post the visitor's details in the
URL). Keyboard focus now stays put in the basket and moves into the header's
popup, and quantities stay within what the server accepts. Paste all three
again, HTML, CSS and JS.

UPDATED 2026-10-07 — languages. Each widget's own text now follows the page's
language (French on /fr/, Arabic on /ar/…), and the basket keeps Duda's
product and option ids, so a product added on the English site reads in French
on /fr/ and links to the French page. Staff still receive every quote in
English, with the customer's language shown on the Quotes page.

To install: in Duda's Widget Builder, open each of the three widgets below and
replace ALL THREE of its HTML, CSS and JS with the blocks here, then publish.
Update all three in one go: each carries a copy of the shared basket code, and
the newest copy takes over whichever widget loads first. Baskets visitors
already have keep working — their older lines show as they were added. The
backend accepts the old and new widgets alike, so nothing breaks in between.

${parts.join("\n")}`;
write(path.join(ROOT, "3-widgets-in-duda.md"), doc);

if (check && stale.length) {
  console.error(`✗ quote widgets are stale — run: node scripts/build-quote-widgets.mjs\n  ${stale.join("\n  ")}`);
  process.exit(1);
}
console.log(check ? "✓ quote widgets: duda-widgets/ and 3-widgets-in-duda.md agree" : "✓ quote widgets built");
